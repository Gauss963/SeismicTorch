"""Export the selected CNN and preprocessing constants as exact C++ literals."""
from pathlib import Path
import argparse
import hashlib
import json
import numpy as np
import torch
from scipy.signal import butter,sosfilt_zi

ROOT=Path(__file__).resolve().parents[2]

def literal(value,single=True):
    x=float(np.float32(value)) if single else float(value)
    return x.hex()+('f' if single else '')

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--candidate',type=Path,default=ROOT/'models/qsis/current')
    parser.add_argument('--output',type=Path,default=ROOT/'cpp/generated/model_weights.hh')
    args=parser.parse_args()
    checkpoint=args.candidate/'model.pth'
    sha=hashlib.sha256(checkpoint.read_bytes()).hexdigest()
    receipt=json.loads((args.candidate/'training.json').read_text())
    if sha!=receipt['checkpoint_sha256'] or receipt['model']!='cnn':raise ValueError('Expected the verified waveform CNN')
    if receipt['waveform_filter']!='steady-start' or receipt['orientation']!={'method':'gravity-v1','calibrations':[]}:
        raise ValueError('Native inference supports steady-start filtering and per-record gravity only')
    state=torch.load(checkpoint,weights_only=True,map_location='cpu')
    arrays={}
    for i in range(1,4):
        scale=state[f'bn{i}.weight']/torch.sqrt(state[f'bn{i}.running_var']+1e-5)
        arrays[f'conv{i}_weight']=(state[f'conv{i}.weight']*scale[:,None,None,None]).numpy()
        arrays[f'conv{i}_bias']=((state[f'conv{i}.bias']-state[f'bn{i}.running_mean'])*scale+state[f'bn{i}.bias']).numpy()
        for field in ('weight','bias'):arrays[f'fc{i}_{field}']=state[f'fc{i}.{field}'].numpy()
    sos=butter(4,.5,btype='highpass',fs=100,output='sos')
    lines=['// Generated by cpp/tools/export_weights.py; do not edit.', '#pragma once','#include <array>','namespace seismictorch::embedded {',f'inline constexpr char checkpoint_sha256[] = "{sha}";','inline constexpr char version[] = "1.0.0";']
    for name,array in arrays.items():
        flat=array.ravel();lines.append(f'inline constexpr std::array<float, {len(flat)}> {name} = {{{{')
        lines.extend('  '+', '.join(literal(v) for v in flat[i:i+6])+',' for i in range(0,len(flat),6))
        lines.append('}};')
    for name,array in [('highpass_sos',sos),('highpass_zi',sosfilt_zi(sos))]:
        flat=array.ravel();lines.append(f'inline constexpr std::array<double, {len(flat)}> {name} = {{{{')
        lines.append('  '+', '.join(literal(v,False) for v in flat));lines.append('}};')
    lines.append('} // namespace seismictorch::embedded')
    args.output.parent.mkdir(parents=True,exist_ok=True);args.output.write_text('\n'.join(lines)+'\n')
    print(f'Exported {sum(a.size for a in arrays.values())} float weights, checkpoint {sha}')

if __name__=='__main__':main()
